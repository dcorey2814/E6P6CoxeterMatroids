"""Data files for the website in docs/.

Writes the five CSV files read by docs/index.html into docs/data/:

  matroid_orbits.csv       data/strata.csv and data/matroid_orbit_reps.dat, with the
                           number of matroids in each orbit
  tropical_fvector.csv     f-vector and cone orbits by dimension, from the gfan output
  ray_orbits.csv           sizes of the W(E6)-orbits of rays, from the gfan output
  maximal_cone_orbits.csv  binomial / prime initial ideal for each maximal-cone orbit
  toric_degenerations.csv  data/toric_degenerations.csv with the degrees of the
                           generators of the initial ideal

The last two also read data/binomial_initial_ideals.txt and data/toric_summary.json,
written with Macaulay2 and Normaliz for the abstract.

  python3 scripts/dashboard_data.py

Needs Python 3 and numpy. W(E6) is generated from the six symmetries in the gfan
output, acting on the 27 lines, to count the matroids in each orbit and the rays in
each ray orbit.
"""
import csv, json, os, re
from collections import Counter
import numpy as np

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
DATA = os.path.join(ROOT, "data")
OUT = os.path.join(ROOT, "docs", "data")

NAMES = [f"a{i}" for i in range(1, 7)] + [f"b{i}" for i in range(1, 7)] + \
        [f"c{i}{j}" for i in range(1, 7) for j in range(i + 1, 7)]


def write_csv(name, header, rows):
    with open(os.path.join(OUT, name), "w", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(header)
        w.writerows(rows)
    print("wrote docs/data/" + name)


def read_gfan(path):
    sections, cur = {}, None
    for line in open(path):
        s = line.rstrip("\n")
        if re.fullmatch(r"[A-Z_]+", s):
            cur = s
            sections[cur] = []
        elif cur is not None and s.strip():
            sections[cur].append(s)
    return sections


def weyl_group(gens):
    """All elements of the group generated by gens, as permutations of 0..26."""
    ident = tuple(range(27))
    seen, frontier = {ident}, [ident]
    while frontier:
        nxt = []
        for p in frontier:
            for g in gens:
                q = tuple(g[p[i]] for i in range(27))
                if q not in seen:
                    seen.add(q)
                    nxt.append(q)
        frontier = nxt
    return np.array(sorted(seen), dtype=np.int64)


def main():
    os.makedirs(OUT, exist_ok=True)

    gfan = read_gfan(os.path.join(DATA, "gfan", "cayley_plane_trop.dat"))
    gens = [tuple(map(int, l.split())) for l in gfan["SYMMETRY_GENERATORS"]]
    G = weyl_group(gens)
    assert len(G) == 51840, len(G)

    # matroid orbits
    reps = [list(map(int, l.split())) for l in open(os.path.join(DATA, "matroid_orbit_reps.dat")) if l.strip()]
    strata = list(csv.DictReader(open(os.path.join(DATA, "strata.csv"))))
    assert len(reps) == len(strata)
    rows = []
    for row, r in zip(strata, reps):
        assert int(row["size"]) == len(r)
        imgs = G[:, [x - 1 for x in r]]
        n = len(np.unique(np.bitwise_or.reduce(np.left_shift(1, imgs), axis=1)))
        rows.append([row["orbit"], row["size"], row["dim_polytope"],
                     "" if row["dim_stratum"] == "-1" else row["dim_stratum"],
                     row["equations"], row["nonempty"], row["all_primes"], n,
                     " ".join(NAMES[x - 1] for x in r)])
    write_csv("matroid_orbits.csv",
              ["orbit", "lines", "dim_polytope", "dim_stratum", "equations", "realizable",
               "nonempty_every_prime", "matroids_in_orbit", "representative"], rows)
    print("  matroids:", sum(r[7] for r in rows))

    # f-vector and cone orbits by dimension
    fvec = list(map(int, gfan["F_VECTOR"][0].split()))
    lin = int(gfan["LINEALITY_DIM"][0])
    orbits_by_dim, d = Counter(), None
    for l in gfan["CONES_ORBITS"]:
        m = re.search(r"# Dimension (\d+)", l)
        if m:
            d = int(m.group(1))
        orbits_by_dim[d] += 1
    write_csv("tropical_fvector.csv", ["dim_mod_lineality", "dim_projective", "cones", "cone_orbits"],
              [[k, lin + k - 1, fvec[k], orbits_by_dim[lin + k]] for k in range(1, len(fvec))])

    # ray orbits: union-find over rays, rays compared modulo the lineality space
    rays = np.array([list(map(int, l.split("#")[0].split())) for l in gfan["RAYS"]], dtype=float)
    L = np.array([list(map(int, l.split())) for l in gfan["LINEALITY_SPACE"]], dtype=float)
    Qb, _ = np.linalg.qr(L.T)

    def canon(v):
        v = v - Qb @ (Qb.T @ v)
        return tuple(np.round(v / np.linalg.norm(v), 6))

    key = {canon(r): i for i, r in enumerate(rays)}
    parent = list(range(len(rays)))

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    for g in gens:
        gi = np.array(g)
        for i, r in enumerate(rays):
            a, b = find(i), find(key[canon(r[gi])])
            if a != b:
                parent[a] = b
    sizes = Counter(find(i) for i in range(len(rays)))
    double_six = np.zeros(27)
    double_six[:12] = 1          # a1..a6, b1..b6 is a double six
    line = np.zeros(27)
    line[0] = 1
    labels = {}
    for v, name in ((double_six, "Double sixes"), (-double_six, "Complements of double sixes"),
                    (-line, "Complements of lines")):
        if canon(v) in key:
            labels[find(key[canon(v)])] = name
    write_csv("ray_orbits.csv", ["ray_orbit", "rays", "description"],
              [[k, n, labels.get(root, "")]
               for k, (root, n) in enumerate(sorted(sizes.items(), key=lambda t: (t[1], t[0])), 1)])

    # maximal-cone orbits
    prime = {}
    for l in open(os.path.join(DATA, "binomial_initial_ideals.txt")):
        if l.strip():
            i, _lattice, _rank, varsat = l.strip().split("|")
            prime[int(i)] = varsat == "true"
    toric = list(csv.DictReader(open(os.path.join(DATA, "toric_degenerations.csv"))))
    by_orbit = {int(t["orbit"]): t for t in toric}
    assert {i + 1 for i, p in prime.items() if p} == set(by_orbit)
    write_csv("maximal_cone_orbits.csv", ["orbit", "binomial_initial_ideal", "prime", "known_polytope"],
              [[i + 1, str(i in prime).lower(), str(prime.get(i, False)).lower(),
                by_orbit[i + 1]["polytope"] if prime.get(i, False) else ""]
               for i in range(len(gfan["MAXIMAL_CONES_ORBITS"]))])

    # toric degenerations
    summary = json.load(open(os.path.join(DATA, "toric_summary.json")))
    known = {"order": "Order polytope (Hibi)", "chain": "Chain polytope"}
    rows = []
    for t in toric:
        s = summary[str(int(t["orbit"]) - 1)]
        degrees = dict((deg, n) for deg, n in s[6])
        fv = t["f_vector"].split()
        assert int(fv[-1]) == int(t["facets"]) == s[0]
        assert (degrees.get(3, 0) == 0) == (t["quadratic"] == "true")
        rows.append([t["orbit"], t["facets"], fv[1], t["lattice_points"], t["normalized_volume"],
                     t["normal"], t["h_star"], degrees.get(2, 0), degrees.get(3, 0),
                     known.get(t["polytope"], ""), t["f_vector"]])
    write_csv("toric_degenerations.csv",
              ["orbit", "facets", "edges", "lattice_points", "normalized_volume", "normal", "h_star",
               "quadric_generators", "cubic_generators", "known_polytope", "f_vector"], rows)


if __name__ == "__main__":
    main()
