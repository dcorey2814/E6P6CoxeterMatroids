# The toric degenerations of E6/P6 (Theorem 4.2 and Table 2).
#
# For each of the 421 orbits of maximal cones, computes the initial ideal and
# tests whether it is prime. For the prime ones, writes the invariants of the
# polytope to data/toric_degenerations.csv, and compares the polytope with the
# order polytope and the chain polytope of the minuscule poset.
#
#   julia --project=. scripts/toric_degenerations.jl

include(joinpath(@__DIR__, "..", "src", "E6P6CoxeterMatroids.jl"))

polytopes = []
open(joinpath(datadir, "toric_degenerations.csv"), "w") do io
    println(io, "orbit,facets,lattice_points,normalized_volume,normal,h_star,quadratic,polytope,f_vector")
    for (i, c) in enumerate(max_cones_OP2)
        J = in_w(vec_rep(c))
        is_prime_binomial(J) || continue
        A, _ = toric_configuration_matrix(J)
        P = convex_hull(matrix(QQ, toric_points(A)))
        push!(polytopes, P)
        t = toric_invariants(P)

        # Is J generated by the quadrics in its reduced Gröbner basis?
        G = collect(groebner_basis(J, complete_reduction = true))
        quadratic = J == ideal(R, [f for f in G if total_degree(f) == 2])

        name = !isnothing(lattice_equivalence(toric_points(A), order_polytope_points)) ? "order" :
               !isnothing(lattice_equivalence(toric_points(A), chain_polytope_points)) ? "chain" : ""

        row = (i, t.facets, t.lattice_points, t.normalized_volume, t.normal,
               join(t.h_star, " "), quadratic, name, join(t.f_vector, " "))
        println(io, join(row, ","))
        println("orbit $i is prime")
    end
end

# Combinatorial types of the polytopes, using polymake through Oscar.
types = []
for P in polytopes
    any(T -> pm.polytope.isomorphic(Oscar.pm_object(P), Oscar.pm_object(T)), types) || push!(types, P)
end
println(length(polytopes), " prime orbits, ", length(types), " combinatorial types of polytopes")
