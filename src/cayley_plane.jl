# The E6-Grassmannian E6/P6 in P^26 and its affine charts (Section 3.1).

# --- Coordinates and equations ----------------------------------------------

# One coordinate p_l for each of the 27 lines l, named after the line.
R, abc = polynomial_ring(QQ, line_labels)
(a1,a2,a3,a4,a5,a6,b1,b2,b3,b4,b5,b6,c12,c13,c14,c15,c16,c23,c24,c25,c26,c34,c35,c36,c45,c46,c56) = abc

as = [a1,a2,a3,a4,a5,a6]
bs = [b1,b2,b3,b4,b5,b6]
cs = [c12,c13,c14,c15,c16,c23,c24,c25,c26,c34,c35,c36,c45,c46,c56]

C = matrix(R,
[0     c12 c13  c14 c15 c16 ;
 -c12  0   c23  c24 c25 c26 ;
 -c13 -c23 0    c34 c35 c36 ;
 -c14 -c24 -c34 0   c45 c46 ;
 -c15 -c25 -c35 -c45   0   c56 ;
 -c16 -c26 -c36 -c46   -c56 0
 ]);

av = matrix([a1; a2; a3; a4; a5; a6]);
bv = matrix([b1; b2; b3; b4; b5; b6]);

"The E6-invariant cubic D = a^T C b + Pf(C): one monomial for each tritangent plane."
D = (transpose(av) * C * bv)[1] + pfaffian(C);

"The ideal of E6/P6 in P^26, generated by the 27 quadrics D_y = dD/dp_y."
I = ideal(R, [derivative(D, x) for x in abc]);

# --- Cross polytopes in terms of the coordinates ----------------------------

position_abc = Dict(abc[i] => i for i in 1:27)
position_a = Dict(as[i] => i for i in 1:6)
position_b = Dict(bs[i] => i for i in 1:6)

n62 = sort(collect(subsets(6,2)))
position_c = Dict(cs[i] => n62[i] for i in 1:15)
cs_d = Dict(n62[i] => cs[i] for i in 1:15)

"""
    opposite_cross_polytope(x)

The 10 coordinates of the lines meeting `x`, written out explicitly:
a_i meets b_j and c_ij (j != i); b_i meets a_j and c_ij (j != i);
c_ij meets a_i, a_j, b_i, b_j and the c_kl with {k,l} disjoint from {i,j}.
Same as `abc[lozenge(y)]` up to order.
"""
function opposite_cross_polytope(x)
    if x in as
        i = position_a[x]
        chart = vcat([bs[j] for j in 1:6 if j!=i], [cs_d[sort([i,j])] for j in 1:6 if j!= i])
    elseif x in bs
        i = position_b[x]
        chart = vcat([as[j] for j in 1:6 if j!=i], [cs_d[sort([i,j])] for j in 1:6 if j!= i])
    else
        i, j = position_c[x]
        chart = vcat([as[i], as[j], bs[i], bs[j]] , [cs_d[sort([k,l])] for k in 1:6, l in 1:6 if !any([k >= l, k in [i,j], l in [i,j]]) ])
    end
    return chart
end

"The chart `y` in `Q` whose opposite cross polytope contains the most elements of `Q`."
function choose_best_chart(Q)
    best = opposite_cross_polytope(Q[1])
    best_n = length(intersect(best, Q))
    best_b = Q[1]
    for x in Q
        V = opposite_cross_polytope(x)
        n = length(intersect(V, Q))
        if n > best_n
            best = V
            best_n = n
            best_b = x
        end
    end
    return best_b
end

# --- The big cell (Theorem 3.1) ---------------------------------------------

"Split `poly` as (v, g) with `poly` = ±(v - g), where v is a variable; (nothing, poly) if it has no linear term."
function separate_single_var(poly)
    for t in terms(poly)
        if total_degree(t) == 1
            lc = leading_coefficient(t)
            rest = poly - t
            return t/lc, -rest/lc
        end
    end
    return nothing, poly
end

"The 27 quadrics D_w with the coordinate `x` set to 1."
function reduce_I(x)
    i = position_abc[x]
    g_vars = []
    for j in 1:27
        if j==i
            push!(g_vars, R(1))
        else
            push!(g_vars, abc[j])
        end
    end
    g = hom(R, R, g_vars)
    return gens(g(I))
end

"""
    isolate_vars(y)

The chart U_y = {p_y != 0}: a dictionary `v => g_v` giving each coordinate
`v` in lozenge(y) as a quadric `g_v` in the 16 coordinates of N(y).
"""
function isolate_vars(x)
    Ired = reduce_I(x)
    h_vars_dict = Dict()
    for f in Ired
        t, r = separate_single_var(f)
        if isnothing(t)
            continue
        end
        h_vars_dict[t] = r
    end
    return h_vars_dict
end

"""
    verify_big_cell(y)

Check Theorem 3.1 in the chart `y`: after substituting p_y = 1 and p_v = g_v,
all 27 quadrics D_w vanish identically, so A^16 -> U_y is an isomorphism.
"""
function verify_big_cell(y)
    g = isolate_vars(y)
    psi = hom(R, R, [x == y ? R(1) : get(g, x, x) for x in abc])
    return all(iszero(psi(f)) for f in gens(I))
end
